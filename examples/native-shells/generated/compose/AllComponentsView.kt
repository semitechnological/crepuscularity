object CrepusActions {
    val knownActions: Set<String> = setOf("import_files", "pick_media", "refresh", "sync.photos")
    var dispatch: (String) -> String = { "{}" }
    var resultSink: (String) -> Unit = {}

    fun perform(action: String) {
        if (!knownActions.contains(action)) {
            resultSink("{\"ok\":false,\"error\":\"unknown generated action\"}")
            return
        }
        resultSink(dispatch(action))
    }
}

