import SwiftUI

public enum CrepusActions {
    public static let knownActions: Set<String> = ["import_files", "pick_media", "refresh", "sync.photos"]
    public static var dispatch: (String) -> String = { _ in "{}" }
    public static var resultSink: (String) -> Void = { _ in }

    public static func perform(_ action: String) {
        guard knownActions.contains(action) else {
            resultSink("{\"ok\":false,\"error\":\"unknown generated action\"}")
            return
        }
        resultSink(dispatch(action))
    }
}

